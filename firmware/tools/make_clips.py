"""Generate the HealthWatch workout audio (counts 1-50 and fixed phrases) as a C header.

The clips are synthesized with Amazon Polly (neural, Kazuha, 8 kHz PCM) and
embedded so that a workout needs no network. Leading and trailing silence is cut.
Usage: uv run --with boto3 python firmware/tools/make_clips.py
Needs AWS credentials that may call polly:SynthesizeSpeech in ap-northeast-1.
"""

import array
from pathlib import Path

import boto3

OUT = Path(__file__).resolve().parent.parent / "src" / "hw" / "clips.h"
RATE = 8000
THRESHOLD = 200  # amplitude below this counts as silence
PAD = 320  # samples kept around the voiced part (40 ms)
LIMIT_BYTES = 700_000

DIGITS = ["", "いち", "に", "さん", "よん", "ご", "ろく", "なな", "はち", "きゅう"]
TENS = ["", "じゅう", "にじゅう", "さんじゅう", "よんじゅう", "ごじゅう"]
PHRASES = {
    "CLIP_START": "スタート",
    "CLIP_DONE": "おつかれさま！",
    "CLIP_HARD": "ややきつくして",
    "CLIP_EASY": "楽にして",
    "CLIP_NEXT": "次の種目",
}


def reading(n: int) -> str:
    return TENS[n // 10] + DIGITS[n % 10]


def synthesize(polly, text: str) -> array.array:
    res = polly.synthesize_speech(
        Text=text,
        Engine="neural",
        VoiceId="Kazuha",
        LanguageCode="ja-JP",
        OutputFormat="pcm",
        SampleRate=str(RATE),
    )
    pcm = array.array("h")
    pcm.frombytes(res["AudioStream"].read())  # Polly PCM is little-endian
    return pcm


def trim(pcm: array.array) -> array.array:
    loud = [i for i, v in enumerate(pcm) if abs(v) >= THRESHOLD]
    if not loud:
        return pcm
    return pcm[max(0, loud[0] - PAD) : loud[-1] + 1 + PAD]


def emit(lines: list[str], name: str, pcm: array.array) -> None:
    lines.append(f"static const int16_t {name}[] = {{")
    for i in range(0, len(pcm), 24):
        lines.append(",".join(str(v) for v in pcm[i : i + 24]) + ",")
    lines.append("};")


def main() -> None:
    polly = boto3.Session(region_name="ap-northeast-1").client("polly")
    lines = [
        "// Generated by tools/make_clips.py with Amazon Polly (Kazuha, neural).",
        "#pragma once",
        "#include <stdint.h>",
        "struct Clip { const int16_t* data; uint32_t samples; };",
        f"constexpr uint32_t CLIP_RATE = {RATE};",
    ]
    clips: dict[str, array.array] = {f"CLIP_NUM_{n}": trim(synthesize(polly, reading(n))) for n in range(1, 51)}
    for name, text in PHRASES.items():
        clips[f"{name}_DATA"] = trim(synthesize(polly, text))
    total = sum(len(p) * 2 for p in clips.values())
    if total > LIMIT_BYTES:
        raise SystemExit(f"audio totals {total} bytes, over the limit of {LIMIT_BYTES}")
    for name, pcm in clips.items():
        emit(lines, "DATA_" + name, pcm)
    lines.append("static const Clip CLIP_NUM[51] = {{nullptr, 0},")
    for n in range(1, 51):
        d = clips[f"CLIP_NUM_{n}"]
        lines.append(f"  {{DATA_CLIP_NUM_{n}, {len(d)}}},")
    lines.append("};")
    for name in PHRASES:
        d = clips[f"{name}_DATA"]
        lines.append(f"static const Clip {name} = {{DATA_{name}_DATA, {len(d)}}};")
    OUT.write_text("\n".join(lines) + "\n")

    nums = [len(clips[f"CLIP_NUM_{n}"]) / RATE for n in range(1, 51)]
    print(f"wrote {OUT}: {total} bytes of audio (limit {LIMIT_BYTES})")
    print(f"numbers: {min(nums):.2f}-{max(nums):.2f} s; phrases: "
          + ", ".join(f"{k}={len(clips[k + '_DATA']) / RATE:.2f}s" for k in PHRASES))


if __name__ == "__main__":
    main()
