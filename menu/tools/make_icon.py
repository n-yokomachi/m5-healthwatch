"""Generate the HealthWatch launcher icon (200x200 RGB565 LVGL image):
a frosted-glass dumbbell with a coral glow on black.
The C array is named after the output file (icon_health.c -> icon_health_map / icon_health).
Usage: uv run --with pillow python tools/make_icon.py [--out main/assets/images/icon_health.c]
"""

import argparse
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE.parent / "main" / "assets" / "images" / "icon_health.c"
SIZE = 200


SS = 4  # supersample for smooth edges


def to_rgb565(im: Image.Image) -> list[int]:
    im = im.resize((SIZE, SIZE), Image.LANCZOS)
    return [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in im.get_flattened_data()]


def glass(shape: Image.Image, color: tuple[int, int, int]) -> Image.Image:
    """Frosted-glass layer on black: tinted glow, gradient body and a soft white rim for a mask."""
    S = SIZE * SS
    glow = shape.filter(ImageFilter.GaussianBlur(9 * SS)).point(lambda v: int(v * 0.85 * 1.2))
    layer = Image.composite(Image.new("RGB", (S, S), color), Image.new("RGB", (S, S), (0, 0, 0)), glow)
    top, bot = (250, 250, 252), tuple(int(c * 0.55 + 90 * 0.45) for c in color)
    body = Image.new("RGB", (S, S))
    bd = ImageDraw.Draw(body)
    for y in range(S):
        t = y / S
        bd.line([(0, y), (S, y)], fill=tuple(int(top[i] * (1 - t) + bot[i] * t) for i in range(3)))
    layer = Image.composite(body, layer, shape.point(lambda v: int(v * 0.9)))
    rim = ImageChops.subtract(shape, shape.filter(ImageFilter.MinFilter(2 * SS + 1))).filter(
        ImageFilter.GaussianBlur(0.6 * SS))
    return Image.composite(Image.new("RGB", (S, S), (255, 255, 255)), layer, rim.point(lambda v: int(v * 0.75)))


def dumbbell_rgb565() -> list[int]:
    S, k, cy, narrow = SIZE * SS, SS, 100, 0.75  # narrow: every x scaled around the centre

    def x(v: float) -> float:
        return 100 + (v - 100) * narrow

    def pill(d: ImageDraw.ImageDraw, x0: float, x1: float, half_h: float, r: float) -> None:
        d.rounded_rectangle((x0 * k, (cy - half_h) * k, x1 * k, (cy + half_h) * k), radius=r * k, fill=255)

    m = Image.new("L", (S, S), 0)
    d = ImageDraw.Draw(m)
    for x0, x1, half_h, r in [(22, 52, 52, 12), (148, 178, 52, 12), (56, 78, 34, 9), (122, 144, 34, 9), (76, 124, 9, 6)]:
        pill(d, x(x0), x(x1), half_h, min(r, (x(x1) - x(x0)) / 2 - 0.5))  # outer plates, inner plates, bar
    layer = glass(m, (255, 90, 70))
    hl = Image.new("L", (S, S), 0)  # highlight on the outer plates
    hd = ImageDraw.Draw(hl)
    for x0 in (30, 156):
        hd.rounded_rectangle((x(x0) * k, (cy - 38) * k, (x(x0) + 6 * narrow) * k, (cy + 20) * k), radius=3 * narrow * k, fill=255)
    layer = Image.composite(Image.new("RGB", (S, S), (255, 255, 255)), layer, hl.point(lambda v: int(v * 0.55)))
    return to_rgb565(layer)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--preview", type=Path, help="also write a PNG preview")
    args = ap.parse_args()
    out, name = args.out, args.out.stem
    pixels = dumbbell_rgb565()
    if args.preview:
        im = Image.new("RGB", (SIZE, SIZE))
        im.putdata([(((v >> 11) << 3), (((v >> 5) & 63) << 2), ((v & 31) << 3)) for v in pixels])
        im.save(args.preview)
    data = []
    for v in pixels:  # LV_COLOR_FORMAT_RGB565 is little-endian
        data += [v & 0xFF, v >> 8]
    body = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 19]) for i in range(0, len(data), 19))
    out.write_text(f"""// Generated by tools/make_icon.py. Do not edit.
#include "lvgl.h"

const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{
{body},
}};

const lv_image_dsc_t {name} = {{
    .header.cf    = LV_COLOR_FORMAT_RGB565,
    .header.magic = LV_IMAGE_HEADER_MAGIC,
    .header.w     = {SIZE},
    .header.h     = {SIZE},
    .data_size    = {SIZE * SIZE * 2},
    .data         = {name}_map,
}};
""")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
